"""Render data/results/backtest.json as docs/backtest-results.md. Stdlib only."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = json.loads((ROOT / "data" / "results" / "backtest.json").read_text())
S = R["setup"]
NAMES = {"none": "No hedge", "naive": "Naive: £20 on Sat and Sun every weekend", "ours": "Ours: cashflow-triggered LP",
         "ours_caps_x5": "Ours, caps x5 (sensitivity)"}
ROWS = [("hedge_net_gbp_per_year", "Net hedge result, £/pub-year", 0), ("premium_gbp_per_year", "Premium paid, £/pub-year", 0),
        ("payouts_gbp_per_year", "Payouts, £/pub-year", 0), ("shortfall_weeks_per_year", "Payroll-shortfall weeks/pub-year", 1),
        ("shortfall_depth_gbp_per_year", "Shortfall depth, £/pub-year", 0), ("worst_week_gbp", "Worst week, £", 0),
        ("worst_month_gbp", "Worst 4-week period, £", 0), ("losing_months_per_year", "Losing 4-week periods/pub-year", 1),
        ("weekly_cash_sd_gbp", "Weekly cash s.d., £", 0), ("cvar5_weekly_gbp", "5% CVaR of weekly cash, £", 0)]


def f(v, nd):
    return f"{v:,.{nd}f}".replace("-", "−")


def g(v):
    return ("+" if v > 0 else "−" if v < 0 else "") + f"£{abs(v):,.0f}"


def main():
    pol = R["policies"]
    head = "| Metric | " + " | ".join(NAMES[p] for p in pol) + " |\n|---|" + "---|" * len(pol) + "\n"
    body = ""
    for k, label, nd in ROWS:
        body += f"| {label} | " + " | ".join(f"{f(pol[p]['point'][k], nd)} [{f(pol[p]['ci95'][k][0], nd)}, "
                                             f"{f(pol[p]['ci95'][k][1], nd)}]" for p in pol) + " |\n"
    hedged = " | ".join(f"{pol[p]['weeks_hedged_all']} / {pol[p]['pub_weeks']}" for p in pol)
    o, n, v = pol["ours"]["point"], pol["naive"]["point"], pol["none"]["point"]
    oc = pol["ours"]["ci95"]
    md = f"""# Backtest on unseen months

**Synthetic takings, real weather.** The takings and bank feeds are SYNTHETIC (generated by
`scripts/gen_synthetic.py`, seed in `data/synthetic/manifest.json`), driven by real Open-Meteo weather, real
match days and real duty-change dates. The rain contract is SYNTHETIC too: no London rain market exists on
Polymarket, so prices come from a stated rule. **This is not real-world performance**, and no real pub's
figures are involved.

## Setup

- **Split by time.** Regression and rain-probability calibration use {S['train'][0]} to {S['train'][1]} only.
  The test window, {S['test'][0]} to {S['test'][1]} (24 months), was never seen by the policy.
- **Decisions use only what was knowable.** Each Thursday the policy sees the archived forecast for Saturday and
  Sunday afternoon (Open-Meteo historical forecast API), the scheduled payments for the next 8 days and the model
  fitted on training years. The archive keeps the most recent forecast per day, so its lead time is shorter than
  two days: forecast skill here is, if anything, optimistic.
- **Panel:** {S['pubs']} synthetic pubs across 4 London locations (N4, SE22, E2, W12), varying size and garden share.
- **Contract:** pays £1 a share if at least {S['contract_mm']:g} mm of rain falls 12:00–18:00 at the pub's grid point.
- **Price rule (SYNTHETIC):** the probability calibrated on training years from archived forecast vs observed rain,
  plus a {S['venue_margin']:.0%} venue margin and a {S['spread'] / 2:.0%} half-spread.
- **Costs:** {S['slippage']:.0%} slippage on the fill, plus Polymarket's weather taker fee, `C × {S['fee_rate']} × p × (1−p)`
  (docs.polymarket.com/trading/fees, checked 7 Nov 2026).
- **Cash model:** VAT goes to a separate account as takings settle. The owner keeps a £5,000 buffer (scaled by pub
  size) plus fixed costs due in the next 10 days, and sweeps the rest to savings every Monday.
- **Policies:**
  - No hedge.
  - Naive: £{S['naive_stake_gbp_per_day']:g} on each of Saturday and Sunday, every weekend.
  - Ours: each Thursday, project next Friday's payroll with the same cashflow engine the kit scores. If a wet
    weekend ({S['wet_scenario_mm']:g} mm each afternoon) would make payroll fail, size with the LP under the caps
    (£{S['limits_gbp']['weekly']:g}/week, £{S['limits_gbp']['monthly']:g}/month, £{S['limits_gbp']['market']:g}/market).
    Otherwise buy nothing.
  - Ours with caps ×5, as a sensitivity check.
- **Uncertainty:** {S['bootstrap']}; 95% intervals in brackets. Blocks are contiguous, so weeks at the very
  start and end of the window are slightly under-sampled (the naive premium interval sits just above its point
  estimate for that reason). "Period" metrics use rolling 4-week windows of operating cash before the owner's
  Monday sweep; no 4-week window lost money, so the risk shows up in single weeks, not months. Worst week and
  worst period are the worst across the whole panel.

## Results (per pub-year, test window only)

{head}{body}| Pub-weeks with a hedge | {hedged} |

## What the data says

- **Hedging every weekend costs money.** The naive policy loses £{-n['hedge_net_gbp_per_year']:,.0f} a pub-year.
  Ours nets {g(o['hedge_net_gbp_per_year'])} a pub-year (95% CI {g(oc['hedge_net_gbp_per_year'][0])} to
  {g(oc['hedge_net_gbp_per_year'][1])}): **indistinguishable from break-even**. It buys in only
  {pol['ours']['weeks_hedged_all']} of {pol['ours']['pub_weeks']} pub-weeks, when a wet weekend would break payroll
  and the contract is cheap enough. The contract is priced near its calibrated probability, so we don't claim an edge.
- **It misses the benchmark that matters.** Ours does not reduce payroll-shortfall weeks
  ({o['shortfall_weeks_per_year']:.1f} against {v['shortfall_weeks_per_year']:.1f} with no hedge), worst week or
  CVaR in any meaningful way. Raising the caps five-fold doesn't change that.
- **Why:** in this model most shortfalls are a few thousand pounds deep, driven by fixed costs and quiet trading
  weeks. A weekend rain hedge capped at £60 a market pays out a few hundred pounds at most. The hedge cuts the depth
  of a wet-weekend shortfall. It cannot fix a structural cash gap, and a bigger cash buffer does more.
- **Honest takeaway for the pitch:** the product's value on this evidence is the warning ("payroll on Friday won't
  clear; here's by how much"), with cheap, small, capped protection for the weather-driven part. It is not a
  profit engine. The numbers below are the real outputs of this run.

## Deck-ready block (replaces slide 11 placeholders)

> **Backtest · 12 synthetic pubs · held-out Nov 2024–Oct 2026 · real weather, synthetic takings and contract prices**
>
> | | Ours | Naive weekly hedge |
> |---|---|---|
> | Net result per pub per year | {g(o['hedge_net_gbp_per_year'])} | {g(n['hedge_net_gbp_per_year'])} |
> | 95% CI | {g(oc['hedge_net_gbp_per_year'][0])} to {g(oc['hedge_net_gbp_per_year'][1])} | {g(pol['naive']['ci95']['hedge_net_gbp_per_year'][0])} to {g(pol['naive']['ci95']['hedge_net_gbp_per_year'][1])} |
> | Payroll-shortfall weeks per year (no hedge: {v['shortfall_weeks_per_year']:.1f}) | {o['shortfall_weeks_per_year']:.1f} | {n['shortfall_weeks_per_year']:.1f} |
> | Weeks hedged | {pol['ours']['weeks_hedged_all']} of {pol['ours']['pub_weeks']} | {pol['naive']['weeks_hedged_all']} of {pol['naive']['pub_weeks']} |
>
> Caption: "Synthetic takings driven by real London weather; synthetic rain-contract prices with real Polymarket
> fees. Our policy is about break-even ({g(o['hedge_net_gbp_per_year'])}/yr, CI {g(oc['hedge_net_gbp_per_year'][0])} to
> {g(oc['hedge_net_gbp_per_year'][1])}) against {g(n['hedge_net_gbp_per_year'])}/yr for hedging every weekend, but it does not
> cut payroll-shortfall weeks at these caps. The warning is the product."

Reproduce: `uv run --project services/agents python scripts/backtest.py && python3 scripts/backtest_report.py`
"""
    (ROOT / "docs" / "backtest-results.md").write_text(md)


if __name__ == "__main__":
    main()
